// 「発行元が利用を許諾していない」と人が判断したライセンス原文の台帳（2026-10-21・#293）。
//
// ライセンス区分（derive-app-data.ts の `licenseClassOf`）は原文の語彙で決まる。利用を認める述語が
// 1つも無い原文 — 市サイトに著作権・利用条件の条項が無くフッターの `Copyright … All rights reserved`
// だけの市、権利の所在だけを述べる市、転載の前に問い合わせ・届け出・許可申請を求めるだけの市 — は
// 語彙に当たらず `unverified` に落ちる。
// ⚠ 笛吹市議会の「引用転載許可申請書…を市長へ提出」は許可の要求そのものだが、語彙（`許可申請`）を足すと
//   全 registry の実測が要るので、ここに載せて閉じている。語彙を足すときはこの行を外す（derive が「要らない行」で知らせる）。
// ⚠ 松阪の「二次利用に際しては…侵害しないよう、ご注意ください」は四日市と冒頭が同じだが、引用の条件も
//   「認める」述語も無いので閉じる側（四日市は引用の条件を示すので台帳の外）。
// ⚠ **`unverified` は画面では open と同じ経路**（自サーバーの原本コピーを開く）なので、
// 放っておくと**開ける側へ倒れる**。
//
// 2026-10-21 に人が決めた: **条項が無い＝許諾が無い、と読んで要許可へ倒す**。写しは残し、
// 画面のリンクは発行元へ振り替える（要許可と同じ扱い）。ここに載っている原文の資料は、
// 語彙によらず `permission-required` になる。
//
// 2026-10-22 に人が決めた: **利用を許諾する規約の本文があるなら、フッターの `Copyright … All rights reserved` より本文を優先する**
// （江南 R8・R7・丸亀・昭島 R8 は本文の原文で open、門真は条件つきの許諾で unverified・docs §13-59）。この台帳は「本文が無い」市だけのもの。
//
// ---- 書くときのルール ----------------------------------------------------------
//
// 1. **`license` は registry の `license` と1字違わず同じ文字列**にする（完全一致で引く）。
//    要約・意訳しない。registry の原文を直したら、ここも直す（derive が両方向で照合する）。
// 2. **閉じる向きにしか使わない。** 語彙で open に当たる原文を載せたら derive が throw する
//    （規約が割れている＝人が原文を読み直す）。語彙だけで要許可に落ちる原文を載せても throw する
//    （要らない行は、のちに語彙を直したときの手掛かりを曇らせる）。
// 3. **条件つきで利用を認める原文は載せない**（名古屋の「改変しない・著作権者を明記する」、
//    四日市の「引用元を明記・改変しない」）。許諾はあるので、この台帳の判断の外にある。
// 4. **型に名前を付けない・件数を書かない**（件数の正は `public/coverage.json`）。
// 5. どの registry の資料にも当たらない行があると derive が throw する（静かに腐らない）。

